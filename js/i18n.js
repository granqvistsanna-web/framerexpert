let currentLang = localStorage.getItem('framerexpert-lang') || 'sv';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('framerexpert-lang', lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang] && translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  const pageId = document.body.dataset.page || 'home';
  const titleKey = 'page.' + pageId + '.title';
  const descKey = 'page.' + pageId + '.description';

  if (translations[lang][titleKey]) {
    document.title = translations[lang][titleKey];
  }

  var metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && translations[lang][descKey]) {
    metaDesc.content = translations[lang][descKey];
  }

  document.querySelectorAll('[data-lang]').forEach((el) => {
    el.classList.toggle('is-active', el.dataset.lang === lang);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);

  var toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.addEventListener('click', () => {
      setLanguage(currentLang === 'sv' ? 'en' : 'sv');
    });
  }
});
